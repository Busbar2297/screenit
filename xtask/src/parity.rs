//! Parity catalog validation and generation of docs/parity-checklist.md and docs/scorecard.md.

use serde::Deserialize;
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::process::Command;

#[derive(Deserialize)]
struct Catalog {
    row: Vec<Row>,
}

#[derive(Deserialize)]
struct Row {
    id: String,
    group: String,
    title: String,
    tier: u8,
    status: String,
    #[serde(default)]
    commands: Vec<String>,
    #[serde(default)]
    tests: Vec<String>,
}

fn registry_ids() -> Option<Vec<String>> {
    let out = Command::new("cargo")
        .args(["run", "-q", "-p", "screenit-cli", "--", "commands", "--ids"])
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    Some(
        String::from_utf8_lossy(&out.stdout)
            .lines()
            .map(|l| l.trim().to_string())
            .collect(),
    )
}

fn weight(r: &Row) -> f64 {
    match r.status.as_str() {
        "done" => 1.0,
        "partial" => 0.5,
        _ => 0.0,
    }
}

pub fn run(scorecard: bool) -> Result<(), String> {
    let text = std::fs::read_to_string("parity/snagit.toml").map_err(|e| e.to_string())?;
    let cat: Catalog = toml::from_str(&text).map_err(|e| e.to_string())?;
    let ids = registry_ids();
    let mut errors = Vec::new();
    for r in &cat.row {
        if !["missing", "partial", "done"].contains(&r.status.as_str()) {
            errors.push(format!("{}: bad status {}", r.id, r.status));
        }
        if r.status != "missing" {
            if r.commands.is_empty() {
                errors.push(format!("{}: {} row lists no commands", r.id, r.status));
            }
            if let Some(ids) = &ids {
                for c in &r.commands {
                    if !ids.contains(c) {
                        errors.push(format!("{}: unknown command {c}", r.id));
                    }
                }
            }
            if r.status == "done" && r.tests.is_empty() {
                errors.push(format!("{}: done row lists no tests", r.id));
            }
        }
    }
    if !errors.is_empty() {
        return Err(errors.join("\n"));
    }
    let total = cat.row.len() as f64;
    let score: f64 = cat.row.iter().map(weight).sum();
    let pct = if total > 0.0 {
        score / total * 100.0
    } else {
        0.0
    };
    let floor: f64 = std::fs::read_to_string("parity/floor.txt")
        .ok()
        .and_then(|s| s.trim().parse().ok())
        .unwrap_or(0.0);
    if pct + 1e-9 < floor {
        return Err(format!(
            "parity {pct:.1}% is below the floor {floor:.1}% (floor never lowers)"
        ));
    }
    if scorecard {
        write_scorecard(&cat, pct, ids.is_some())?;
    } else {
        write_checklist(&cat, pct)?;
    }
    println!("parity: {pct:.1}% (floor {floor:.1}%)");
    Ok(())
}

fn write_checklist(cat: &Catalog, pct: f64) -> Result<(), String> {
    let mut s =
        String::from("# Parity checklist (GENERATED by `cargo xtask parity`, do not edit)\n\n");
    let _ = writeln!(
        s,
        "Weighted parity: **{pct:.1}%** over {} rows.\n",
        cat.row.len()
    );
    let mut groups: BTreeMap<&str, Vec<&Row>> = BTreeMap::new();
    for r in &cat.row {
        groups.entry(&r.group).or_default().push(r);
    }
    for (g, rows) in groups {
        let _ = writeln!(s, "## {g}\n");
        for r in rows {
            let mark = match r.status.as_str() {
                "done" => "[x]",
                "partial" => "[~]",
                _ => "[ ]",
            };
            let _ = writeln!(s, "- {mark} `{}` T{} {}", r.id, r.tier, r.title);
        }
        s.push('\n');
    }
    write("docs/parity-checklist.md", &s)
}

fn write_scorecard(cat: &Catalog, pct: f64, registry_ok: bool) -> Result<(), String> {
    let mut s = String::from("# Scorecard (GENERATED by `cargo xtask scorecard`, do not edit)\n\n");
    let _ = writeln!(
        s,
        "Weighted parity: **{pct:.1}%**. Command registry readable: {registry_ok}.\n"
    );
    s.push_str("| Tier | done | partial | missing |\n|---|---|---|---|\n");
    for t in 0..=3u8 {
        let c = |st: &str| {
            cat.row
                .iter()
                .filter(|r| r.tier == t && r.status == st)
                .count()
        };
        let _ = writeln!(
            s,
            "| {t} | {} | {} | {} |",
            c("done"),
            c("partial"),
            c("missing")
        );
    }
    let budgets = std::fs::read_to_string("perf/budgets.toml").unwrap_or_default();
    s.push_str("\n## Performance budgets\n\n```toml\n");
    s.push_str(&budgets);
    s.push_str("```\n");
    let tested = cat.row.iter().filter(|r| !r.tests.is_empty()).count();
    let _ = writeln!(s, "\nRows with named tests: {tested}/{}.", cat.row.len());
    write("docs/scorecard.md", &s)
}

fn write(path: &str, s: &str) -> Result<(), String> {
    std::fs::write(path, s).map_err(|e| format!("write {path}: {e}"))
}
